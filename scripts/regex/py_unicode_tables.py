"""Generate LeanStarlette/RepoImpl/PyRe/Unicode.lean: the code points that
Python's `re` (str patterns, no flags) puts in `\\d`, `\\w` and `\\s`, found by
testing every scalar value. Run with upstream-spec/.venv/bin/python -I."""
import re, sys

def ranges(pat):
    rx = re.compile(pat)
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if rx.fullmatch(chr(cp)):
            if start is not None and cp == prev + 1:
                prev = cp
            else:
                if start is not None:
                    out.append((start, prev))
                start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out

def emit(name, doc, rs):
    lines = [f"/-- {doc} -/", f"def {name} : Array (Nat × Nat) := #["]
    items = [f"(0x{a:x}, 0x{b:x})" for a, b in rs]
    for i in range(0, len(items), 6):
        lines.append("  " + ", ".join(items[i:i+6]) + ("," if i + 6 < len(items) else "]"))
    return "\n".join(lines)

